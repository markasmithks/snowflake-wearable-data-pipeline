-- Wearable Sensor Data Engineering Prototype
-- 01_setup.sql

-- Create the project database
CREATE DATABASE IF NOT EXISTS WEARABLE_DEMO;

-- Create logical data layers
CREATE SCHEMA IF NOT EXISTS WEARABLE_DEMO.RAW;
CREATE SCHEMA IF NOT EXISTS WEARABLE_DEMO.STAGING;
CREATE SCHEMA IF NOT EXISTS WEARABLE_DEMO.CURATED;

-- Set our working context
USE DATABASE WEARABLE_DEMO;
USE SCHEMA RAW;

-- Verify setup
SELECT
    CURRENT_DATABASE() AS DATABASE_NAME,
    CURRENT_SCHEMA() AS SCHEMA_NAME,
    CURRENT_WAREHOUSE() AS WAREHOUSE_NAME,
    CURRENT_ROLE() AS ACTIVE_ROLE;
