-- 02_create_tables.sql
-- Create raw source tables for wearable sensor data

--USE WAREHOUSE [YOUR NAME];
USE DATABASE WEARABLE_DEMO;
USE SCHEMA RAW;

CREATE TABLE IF NOT EXISTS ANIMALS (
    ANIMAL_ID VARCHAR(20) PRIMARY KEY,
    ANIMAL_NAME VARCHAR(100),
    SPECIES VARCHAR(30),
    BREED VARCHAR(100)
    );

CREATE TABLE IF NOT EXISTS DEVICES (
    DEVICE_ID VARCHAR(20) PRIMARY KEY,
    MANUFACTURER VARCHAR(100),
    DEVICE_TYPE VARCHAR(50)
);

CREATE TABLE IF NOT EXISTS DEVICE_ASSIGNMENTS (
    ASSIGNMENT_ID INTEGER AUTOINCREMENT,
    ANIMAL_ID VARCHAR(20),
    DEVICE_ID VARCHAR(20),
    ASSIGNMENT_START TIMESTAMP_NTZ,
    ASSIGNMENT_END TIMESTAMP_NTZ,
    PRIMARY KEY (ASSIGNMENT_ID)
);


CREATE TABLE IF NOT EXISTS SENSOR_READINGS (
    READING_ID INTEGER AUTOINCREMENT,
    DEVICE_ID VARCHAR(20),
    EVENT_TIMESTAMP TIMESTAMP_NTZ,
    ACTIVITY_COUNT INTEGER,
    INGESTION_TIMESTAMP TIMESTAMP_NTZ
        DEFAULT CURRENT_TIMESTAMP()::TIMESTAMP_NTZ,
    PRIMARY KEY (READING_ID)
);